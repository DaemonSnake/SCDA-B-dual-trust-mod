"""Generate the compiled rule table from the reviewed reference, no game assets."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
reference = json.loads((root / 'knowledge/TRUST_RULES_REFERENCE.json').read_text(encoding='utf8'))
lines = ['// Generated by tools/analysis/generate_trust_rules.py; edit the reference JSON.',
         '#pragma once', '#include <string_view>', 'namespace game::trust {',
         'struct Rule { std::string_view mission, id, label; int nsa, jba; };',
         'inline constexpr Rule kRules[] = {']
for r in reference['rules']:
    if r['kind'] != 'story':
        continue
    section = r['section'].lower()
    mission = 'hq1' if 'hq2' in section else 'hq2' if 'hq5' in section else '_'.join(section.split('_')[1:3])
    # Compact ASCII labels keep HUD notification text legible in the existing font.
    import unicodedata
    label = unicodedata.normalize('NFKD', r['proposal']['label']).encode('ascii', 'ignore').decode()
    quote = lambda s: json.dumps(s, ensure_ascii=True)
    p = r['proposal']
    lines.append('    {' + ', '.join([quote(mission), quote(r['id'].lower()), quote(label), str(p['nsa']), str(p['jba'])]) + '},')
lines += ['};', '}']
(root / 'src/game/trust_rules.h').write_text('\n'.join(lines) + '\n', encoding='utf8')
print('Generated', len(reference['rules']), 'reference entries ->', sum(r['kind']=='story' for r in reference['rules']), 'story rules')
