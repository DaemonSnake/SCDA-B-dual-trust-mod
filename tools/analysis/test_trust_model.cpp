#include "game/trust_model.h"
#include <cassert>
#include <iostream>
using namespace game::trust;
int main() {
    static_assert(Rebalance({5, 0}) == Pair{2, 0});
    static_assert(Rebalance({0, 15}) == Pair{0, 7});
    static_assert(Rebalance({5, 5}) == Pair{2, 2});
    static_assert(Rebalance({-5, 5}) == Pair{-10, 5});
    static_assert(Rebalance({15, -30}) == Pair{15, -40});
    static_assert(Rebalance({-30, 30}) == Pair{-40, 30});
    static_assert(Rebalance({30, -30}) == Pair{30, -40});
    static_assert(Rebalance({0, -15}) == Pair{0, -30});
    State major_loss;
    major_loss.Once("major", Rebalance({-30, 30}));
    assert((major_loss.value == Pair{35, 100}));
    major_loss.Revoke("major");
    assert((major_loss.value == Pair{75, 75}));
    static_assert(Rebalance({-5, -10}) == Pair{-10, -20});
    static_assert(Rebalance({0, 0}) == Pair{0, 0});
    State balanced;
    balanced.Once("free", Rebalance({5, 0}));
    balanced.Once("free", Rebalance({5, 0}));
    assert((balanced.value == Pair{77, 75}));
    balanced.Revoke("free");
    assert((balanced.value == Pair{75, 75}));
    balanced.value = {98, 75};
    balanced.Once("tradeoff", Rebalance({5, -5}));
    assert((balanced.value == Pair{100, 65}));
    balanced.Revoke("tradeoff");
    assert((balanced.value == Pair{98, 75}));
    State s;
    s.Once("intel", {10, 0});
    assert((s.value == Pair{85, 75}));
    s.Once("intel", {10, 0});
    assert((s.value == Pair{85, 75}));
    s.Once("shared", {5, 5});
    assert((s.value == Pair{90, 80}));
    s.Once("spared", {15, -15});
    assert((s.value == Pair{100, 65}));
    s.Revoke("spared");
    assert((s.value == Pair{90, 80}));
    s.Once("killed", {-15, 15});
    assert((s.value == Pair{75, 95}));
    State checkpoint = s;
    s.Change({-100, -100});
    s = checkpoint;
    assert(s.Has("intel") && (s.value == Pair{75, 95}));
    assert(CrisisValue({100, 100}) == 50);
    assert(CrisisValue({10, 90}) == 10);
    assert(CrisisValue({90, 10}) == 90);
    assert(CrisisValue({35, 80}) == 35);
    assert(CrisisValue({80, 35}) == 65);
    assert(CrisisValue({100, 40}) == 61);
    assert(CrisisValue({100, 0}) == 100);
    assert(Mission("x06_cozumel_a") == Mission("x06_cozumel_b"));
    assert(Mission("x05_hq2_r") != Mission("x11_hq5_r"));
    std::array<int, 11> records{};
    records[2] = 1; records[5] = 1;
    assert((StatisticsScore(records, 1) == Pair{-14, 0}));
    assert((StatisticsScore(records, 0) == Pair{0, 0}));
    records = {}; records[0] = 4; records[3] = 1;
    assert((StatisticsScore(records, 2) == Pair{0, 0}));
    records = {}; records[0] = 1;
    assert((StatisticsScore(records, 2) == Pair{0, 0}));
    records[0] = 2;
    assert((StatisticsScore(records, 2) == Pair{1, 0}));
    records = {}; records[7] = 2; records[10] = 1; records[6] = 1;
    assert((StatisticsScore(records, 4 | 8 | 16) == Pair{-10, 0}));
    records = {}; records[2] = 30;
    assert((StatisticsScore(records, 1) == Pair{-60, 0}));
    records[0] = 40;
    assert((StatisticsScore(records, 1 | 2) == Pair{-53, 0}));
    records = {}; records[5] = 5;
    assert((StatisticsScore(records, 1) == Pair{-50, 0}));
    records[5] = 6;
    assert((StatisticsScore(records, 1) == Pair{-60, 0}));
    records[5] = 7;
    assert((StatisticsScore(records, 1) == Pair{-60, 0}));
    records = {}; records[2] = 14;
    assert((StatisticsScore(records, 1) == Pair{-56, 0}));
    records[2] = 15;
    assert((StatisticsScore(records, 1) == Pair{-60, 0}));
    records = {}; records[5] = 6; records[7] = 5; records[10] = 4;
    assert((StatisticsScore(records, 31) == Pair{-60, 0}));
    assert((StatisticsScore(records, 0) == Pair{0, 0}));
    State reckless;
    reckless.Once("statistics", StatisticsScore(records, 31));
    assert((reckless.value == Pair{15, 75}));
    reckless.Once("statistics", StatisticsScore(records, 31));
    assert((reckless.value == Pair{15, 75}));
    records = {}; records[5] = records[0] = records[7] = records[10] = 1;
    assert((StatisticsScore(records, 31) == Pair{-16, 0}));
    State hisham;
    hisham.mission = "x10_kinshasa";
    hisham.Once(Key(hisham, "obj_10_p_30"), Rebalance({15, 0}));
    RecordHishamEvidence(hisham, HishamEvidence::Accepted);
    assert((hisham.value == Pair{82, 75}));
    GrantHishamProof(hisham);
    assert((hisham.value == Pair{82, 77}));
    RecordHishamEvidence(hisham, HishamEvidence::Exposed);
    assert((hisham.value == Pair{82, 45}));
    State oldSave;
    oldSave.mission = "x10_kinshasa";
    oldSave.Once(Key(oldSave, "hisham-no-proof"), {0, -15});
    RecordHishamEvidence(oldSave, HishamEvidence::Exposed);
    assert((oldSave.value == Pair{75, 45}));
    State acceptedSave;
    acceptedSave.mission = oldSave.mission;
    acceptedSave.Once(Key(acceptedSave, "hisham-no-proof"), {0, -15});
    RecordHishamEvidence(acceptedSave, HishamEvidence::Accepted);
    assert((acceptedSave.value == Pair{75, 75}));
    RecordHishamEvidence(hisham, HishamEvidence::Exposed);
    GrantHishamProof(hisham);
    RecordHishamEvidence(hisham, HishamEvidence::Accepted);
    assert((hisham.value == Pair{82, 45}));
    std::cout << "trust model: independent effects, duplicate suppression, saturated reversal, checkpoint copy, crises, integer balance, statistics and Hisham evidence passed\n";
}
